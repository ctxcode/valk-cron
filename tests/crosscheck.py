#!/usr/bin/env python3
# Writes tests/croniter-samples.valk: next and previous times from Python's croniter
# (pip install croniter). Run from the repository root.
#
# Expressions avoid the spots where croniter differs from Vixie cron on purpose: a day field
# that starts with `*` without being `*` next to a restricted other day field, a field that
# lists every value, a range like `5-5`, wrapping ranges with a step, and `a/step` that passes
# the end of the field.
import random
from datetime import datetime
from zoneinfo import ZoneInfo
from croniter import croniter

random.seed(7)
ZONES = ["UTC", "Asia/Tokyo", "Asia/Kolkata", "America/Phoenix"]
MONTHS = ["JAN", "FEB", "MAR", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC"]
DAYS = ["SUN", "MON", "TUE", "WED", "THU", "FRI", "SAT"]

FIXED = [
    "* * * * *", "0 0 * * *", "*/5 * * * *", "0 */2 * * *", "15 10 * * MON-FRI",
    "0 0 1 1 *", "0 0 29 2 *", "0 12 L * *", "0 12 15W * *", "0 12 1W * *", "0 12 31W * *",
    "30 8 * * L5", "30 8 * * MON#2", "0 0 * * SUN#5", "0 0 13 * FRI", "0 0 1,15 * 3",
    "0 22-2 * * *", "0 0 * * FRI-MON", "0 0 * NOV-FEB *", "5/15 * * * *", "0 0 2/10 * *",
    "0 9 * * 7", "0 9 * * 0,7", "0 0 L,15 * *", "0 0 L * MON", "0 0 * * L5,MON#1",
    "0 0 ? * MON", "0 0 1 * ?", "0 0 */40 * *", "1-10/3 */6 * * *",
    "*/10 * * * * *", "0 0 12 * * *", "30 */15 9-17 * * MON-FRI", "0,30 0 0 1 * *",
    "59 59 23 31 12 *", "0 0 0 29 2 MON",
]


def values(low, high, names=None):
    v = random.randint(low, high)
    if names and random.random() < 0.3:
        return names[v - low] if len(names) == high - low + 1 else str(v)
    return str(v)


def names_are_days(names):
    return names is not None and names[0] == "SUN"


def item(low, high, names=None):
    r = random.random()
    if r < 0.45:
        return values(low, high, names)
    if r < 0.7:
        a = random.randint(low, high - 1)
        b = random.randint(a + 1, high)
        if a == low and b == high:
            b -= 1
        if a >= b:
            return str(a)
        text = f"{a}-{b}"
        if random.random() < 0.4:
            text += "/" + str(random.randint(2, 5))
        return text
    if r < 0.85 and not names_are_days(names):
        # croniter wraps `a/step` around when a + step passes the end
        a = random.randint(low, high - 2)
        return f"{a}/{random.randint(2, max(2, high - a))}"
    return f"*/{random.randint(2, 20)}"


def field(low, high, names=None, star=0.4):
    if random.random() < star:
        return "*"
    count = random.choice([1, 1, 1, 2, 3])
    return ",".join(item(low, high, names) for _ in range(count))


def covers_all(text, low, high):
    try:
        expr = croniter(f"0 0 {text} * *" if high == 31 else f"0 0 * * {text}")
        return expr.expanded[2 if high == 31 else 4] == ["*"]
    except Exception:
        return True


def random_expression():
    while True:
        minute = field(0, 59, star=0.2)
        hour = field(0, 23)
        dom = field(1, 31, star=0.6)
        month = field(1, 12, MONTHS, star=0.6)
        dow = field(0, 6, DAYS, star=0.6)
        # Vixie: a day field starting with `*` makes the other one required, croniter ORs them
        if (dom != "*" and dom.startswith("*") and dow != "*") or (dow != "*" and dow.startswith("*") and dom != "*"):
            continue
        if dom != "*" and covers_all(dom, 1, 31):
            continue
        if dow != "*" and covers_all(dow, 0, 6):
            continue
        parts = [minute, hour, dom, month, dow]
        if random.random() < 0.2:
            parts.insert(0, field(0, 59, star=0.3))
        text = " ".join(parts)
        try:
            croniter(text, second_at_beginning=True)
        except Exception:
            continue
        return text


def times(expression, start, zone, forward):
    it = croniter(expression, start, second_at_beginning=True)
    out = []
    for _ in range(5):
        t = it.get_next(datetime) if forward else it.get_prev(datetime)
        out.append(str(int(t.timestamp())))
    return ",".join(out)


def main():
    lines = []
    expressions = FIXED + [random_expression() for _ in range(1000)]
    for i, expression in enumerate(expressions):
        zone = ZONES[i % len(ZONES)]
        stamp = random.randint(946_684_800, 2_208_988_800)
        if i % 5 == 0:
            stamp -= stamp % 3600
        start = datetime.fromtimestamp(stamp, ZoneInfo(zone))
        try:
            after = times(expression, start, zone, True)
            before = times(expression, start, zone, False)
        except Exception as e:
            print("skipped", expression, e)
            continue
        lines.append(f"{expression}|{zone}|{stamp}|{after}|{before}")
    with open("tests/croniter-samples.valk", "w") as f:
        f.write("// Generated by tests/crosscheck.py from Python's croniter: do not edit\n")
        f.write("// expression|zone|start|next five|previous five (Unix seconds)\n")
        f.write("fn croniter_samples() String {\n    return \"")
        f.write("\n".join(lines))
        f.write("\"\n}\n")
    print(len(lines), "samples")


main()
